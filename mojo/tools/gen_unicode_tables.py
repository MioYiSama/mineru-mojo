"""Generate the tokenizer's Unicode categories and canonical NFC data.

Development-only: run with Python to regenerate the checked-in Mojo source.
The executable reads no Python code or Unicode database at runtime.
"""

import unicodedata as ud
from pathlib import Path


def ranges(values):
    result = []
    for cp in values:
        if result and cp == result[-1][1] + 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return result


def packed(rows):
    return ";".join(",".join(map(str, row)) for row in rows)


def generate():
    letters, numbers, spaces, combining, decomp, composition = [], [], [], [], [], []
    for cp in range(0x110000):
        ch = chr(cp)
        category = ud.category(ch)
        if category.startswith("L"):
            letters.append(cp)
        if category.startswith("N"):
            numbers.append(cp)
        # Regex White_Space, unlike Python isspace, excludes U+001C..U+001F.
        if ch.isspace() and not 0x1C <= cp <= 0x1F:
            spaces.append(cp)
        ccc = ud.combining(ch)
        if ccc:
            combining.append([cp, ccc])
        raw = ud.decomposition(ch)
        if raw and not raw.startswith("<"):
            parts = [int(part, 16) for part in raw.split()]
            decomp.append([cp, *parts])
            if len(parts) == 2 and ud.normalize("NFC", "".join(map(chr, parts))) == ch:
                composition.append([parts[0] * 0x110000 + parts[1], cp])
    source = f'''"""Generated by tools/gen_unicode_tables.py; Unicode {ud.unidata_version}."""

from .json import append_utf8

comptime _LETTERS = "{packed(ranges(letters))}"
comptime _NUMBERS = "{packed(ranges(numbers))}"
comptime _SPACES = "{packed(ranges(spaces))}"
comptime _COMBINING = "{packed(combining)}"
comptime _DECOMPOSITIONS = "{packed(decomp)}"
comptime _COMPOSITIONS = "{packed(composition)}"


def _rows(text: String) raises -> List[List[Int]]:
    var result = List[List[Int]]()
    for row in text.split(";"):
        var values = List[Int]()
        for item in row.split(","):
            values.append(Int(item))
        result.append(values^)
    return result^


def _in_ranges(cp: Int, ranges: List[List[Int]]) -> Bool:
    var lo = 0
    var hi = len(ranges)
    while lo < hi:
        var mid = (lo + hi) // 2
        if cp < ranges[mid][0]:
            hi = mid
        elif cp > ranges[mid][1]:
            lo = mid + 1
        else:
            return True
    return False

struct UnicodeTables(Movable):
    var _letters: List[List[Int]]
    var _numbers: List[List[Int]]
    var _spaces: List[List[Int]]
    var _combining: Dict[Int, Int]
    var _decompositions: Dict[Int, List[Int]]
    var _compositions: Dict[Int, Int]

    def __init__(out self) raises:
        self._letters = _rows(_LETTERS)
        self._numbers = _rows(_NUMBERS)
        self._spaces = _rows(_SPACES)
        self._combining = Dict[Int, Int]()
        self._decompositions = Dict[Int, List[Int]]()
        self._compositions = Dict[Int, Int]()
        for row in _rows(_COMBINING):
            self._combining[row[0]] = row[1]
        for row in _rows(_DECOMPOSITIONS):
            var parts = List[Int]()
            for i in range(1, len(row)):
                parts.append(row[i])
            self._decompositions[row[0]] = parts^
        for row in _rows(_COMPOSITIONS):
            self._compositions[row[0]] = row[1]

    def is_letter(self, cp: Int) -> Bool:
        return _in_ranges(cp, self._letters)

    def is_number(self, cp: Int) -> Bool:
        return _in_ranges(cp, self._numbers)

    def is_space(self, cp: Int) -> Bool:
        return _in_ranges(cp, self._spaces)

    def _decompose(self, cp: Int, mut result: List[Int]) raises:
        if cp >= 0xAC00 and cp <= 0xD7A3:
            var s = cp - 0xAC00
            result.append(0x1100 + s // 588)
            result.append(0x1161 + (s % 588) // 28)
            if s % 28:
                result.append(0x11A7 + s % 28)
        elif cp in self._decompositions:
            for part in self._decompositions[cp]:
                self._decompose(part, result)
        else:
            result.append(cp)

    def _compose(self, a: Int, b: Int) -> Int:
        if a >= 0x1100 and a < 0x1113 and b >= 0x1161 and b < 0x1176:
            return 0xAC00 + ((a - 0x1100) * 21 + b - 0x1161) * 28
        if a >= 0xAC00 and a <= 0xD7A3 and (a - 0xAC00) % 28 == 0 and b > 0x11A7 and b < 0x11C3:
            return a + b - 0x11A7
        return self._compositions.get(a * 0x110000 + b, -1)

    def normalize_nfc(self, text: String) raises -> String:
        """Canonical decomposition, stable combining ordering, recomposition."""
        var decomposed = List[Int]()
        for cp in text.codepoints():
            self._decompose(Int(cp), decomposed)
        # Insertion sort only within combining sequences, preserving equal CCC.
        for i in range(1, len(decomposed)):
            var ccc = self._combining.get(decomposed[i], 0)
            if ccc == 0:
                continue
            var j = i
            while j > 0 and self._combining.get(decomposed[j - 1], 0) > ccc:
                var tmp = decomposed[j - 1]
                decomposed[j - 1] = decomposed[j]
                decomposed[j] = tmp
                j -= 1
        var composed = List[Int]()
        var starter = -1
        var previous_ccc = 0
        for cp in decomposed:
            var ccc = self._combining.get(cp, 0)
            var combined = -1
            if starter != -1 and (previous_ccc < ccc or previous_ccc == 0):
                combined = self._compose(composed[starter], cp)
            if combined != -1:
                composed[starter] = combined
            else:
                if ccc == 0:
                    starter = len(composed)
                composed.append(cp)
                previous_ccc = ccc
        var data = List[UInt8](capacity=text.byte_length())
        for cp in composed:
            append_utf8(data, cp)
        return String(unsafe_from_utf8=Span(data))
'''
    destination = (
        Path(__file__).resolve().parents[1] / "mineru_ocr" / "unicode_tables.mojo"
    )
    destination.write_text(source)


if __name__ == "__main__":
    generate()
